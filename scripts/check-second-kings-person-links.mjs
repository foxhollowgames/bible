assert(!linked(8,16,'jehoram-judah'));assert(!linked(8,16,'joram-israel'));
assert(linked(12,1,'joash-judah'));assert(!linked(12,1,'joash-israel'));
assert(linked(13,14,'joash-israel'));assert(!linked(13,14,'joash-judah'));
assert(!linked(13,10,'joash-israel'));assert(!linked(13,10,'joash-judah'));
assert(!linked(14,13,'joash-israel'));assert(!linked(14,13,'joash-judah'));
assert(linked(13,24,'ben-hadad-hazael'));assert(!linked(13,24,'ben-hadad-ahab'));
assert(linked(8,7,'ben-hadad-ahab'));assert(!linked(8,7,'ben-hadad-hazael'));
assert(linked(13,1,'jehoahaz-israel'));assert(!linked(13,1,'jehoahaz-judah'));
assert(linked(23,31,'jehoahaz-judah'));assert(!linked(23,31,'jehoahaz-israel'));
assert(linked(14,23,'jeroboam-ii'));assert(!linked(14,23,'jeroboam'));
assert(linked(14,24,'jeroboam'));assert(!linked(14,24,'jeroboam-ii'));
