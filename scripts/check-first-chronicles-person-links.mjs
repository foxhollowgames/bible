import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../dist/',import.meta.url);
const app=await readFile(new URL('app.js',root),'utf8');
const people=JSON.parse(await readFile(new URL('data/books/1-chronicles-people.json',root),'utf8')).people;
const book=JSON.parse(await readFile(new URL('data/books/1-chronicles.json',root),'utf8'));
const functions=app.slice(app.indexOf('function entityLinkTerms('),app.indexOf('function linkedPersonProfileHtml('));
const places=JSON.parse(await readFile(new URL('data/books/1-chronicles-native-content.json',root),'utf8')).places;
const context=vm.createContext({people,state:{chapter:1},entityLinkCache:{chapter:null,terms:[]},data:{places,regions:[],campaigns:[],events:[],ancientRoads:[],words:[]},mapDisplayName:s=>s,esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(functions,context);
const linked=(chapter,n,id)=>{context.state.chapter=chapter;return context.linkedEntityHtml(book.scripture[chapter].find(v=>v.verse===n).text,{verse:n}).includes(`data-person-id="${id}"`);};
assert(linked(2,12,'obed'));assert(!linked(2,37,'obed'));
assert(linked(2,18,'caleb-hezron'));assert(!linked(2,18,'caleb'));
assert(linked(4,15,'caleb'));assert(!linked(4,15,'caleb-hezron'));
assert(linked(3,15,'zedekiah'));assert(!linked(3,15,'zedekiah-jeconiah'));
assert(linked(3,16,'zedekiah-jeconiah'));assert(!linked(3,16,'zedekiah'));
assert(linked(3,11,'joash-judah'));assert(linked(3,11,'ahaziah-judah'));
assert(linked(3,13,'manasseh-king'));assert(!linked(7,14,'manasseh-king'));
assert(linked(6,3,'miriam'));assert(!linked(4,17,'miriam'));
assert(linked(6,33,'heman-singer'));assert(!linked(2,6,'heman-singer'));
assert(linked(11,12,'eleazar-dodai'));assert(!linked(11,12,'eleazar'));
assert(linked(13,13,'obed-edom'));assert(!linked(13,13,'obed-edom-jeduthun'));
assert(!linked(16,38,'obed-edom'));assert(!linked(16,38,'obed-edom-jeduthun'));
assert(linked(26,4,'obed-edom-gatekeeper'));assert(!linked(26,4,'obed-edom'));
assert(linked(23,15,'gershom-moses'));assert(!linked(6,16,'gershom-moses'));
assert(linked(18,16,'ahimelech-abiathar'));assert(!linked(18,16,'ahimelech'));
assert(linked(20,5,'elhanan-jair'));assert(linked(20,5,'lahmi'));
assert(linked(21,18,'araunah'));assert(linked(7,24,'sheerah'));
const features=(chapter,n)=>{context.state.chapter=chapter;return context.linkedEntityHtml(book.scripture[chapter].find(v=>v.verse===n).text,{verse:n});};
assert(!features(7,14).includes('data-detail-id="gilead"'));
assert(!features(7,19).includes('data-detail-id="shechem"'));
assert(!features(7,34).includes('data-detail-id="aram"'));
assert(!features(6,2).includes('data-detail-id="hebron"'));
assert(features(6,55).includes('data-detail-id="hebron"'));
assert.equal((features(7,24).match(/data-person-id="sheerah"/g)||[]).length,1);
assert(!features(16,38).includes('data-detail-id="edom"'));
console.log('First Chronicles links passed: genealogical namesakes and uncertain identities.');
