import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../dist/',import.meta.url);
const app=await readFile(new URL('app.js',root),'utf8');
const people=JSON.parse(await readFile(new URL('data/books/ezra-people.json',root),'utf8')).people;
const book=JSON.parse(await readFile(new URL('data/books/ezra.json',root),'utf8'));
const functions=app.slice(app.indexOf('function entityLinkTerms('),app.indexOf('function linkedPersonProfileHtml('));
const places=JSON.parse(await readFile(new URL('data/books/ezra-native-content.json',root),'utf8')).places;
const context=vm.createContext({people,state:{chapter:1},entityLinkCache:{chapter:null,terms:[]},data:{places,regions:[],campaigns:[],events:[],ancientRoads:[],words:[]},mapDisplayName:s=>s,esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(functions,context);
const html=(chapter,n)=>{context.state.chapter=chapter;return context.linkedEntityHtml(book.scripture[chapter].find(v=>v.verse===n).text,{verse:n});};
const linked=(chapter,n,id)=>html(chapter,n).includes(`data-person-id="${id}"`);
assert(linked(1,8,'mithredath-treasurer'));assert(!linked(1,8,'mithredath-writer'));
assert(linked(4,7,'mithredath-writer'));assert(!linked(4,7,'mithredath-treasurer'));
assert(linked(2,2,'jeshua-priest'));assert(!linked(2,6,'jeshua-priest'));assert(!linked(2,36,'jeshua-priest'));assert(!linked(2,40,'jeshua-priest'));
assert(linked(3,2,'jeshua-priest'));assert(!linked(3,9,'jeshua-priest'));
assert(!linked(2,2,'rehum-chancellor'));assert(linked(4,8,'rehum-chancellor'));
assert(linked(5,1,'zechariah-prophet'));assert(!linked(8,3,'zechariah-prophet'));assert(!linked(8,16,'zechariah-prophet'));
assert(linked(8,17,'iddo-casiphia'));assert(!linked(5,1,'iddo-casiphia'));
assert(linked(8,33,'eleazar-phinehas'));assert(linked(8,33,'noadiah-ezra'));
assert(linked(8,33,'meremoth'));assert(linked(8,18,'sherebiah'));
assert(linked(10,15,'marriage-objectors'));assert(linked(10,15,'shabbethai'));
assert(linked(10,44,'foreign-wives-children'));
assert(!linked(10,23,'jozabad-ezra'));assert(!linked(10,28,'jehohanan-eliashib'));
assert(!book.places.some(p=>/ahava|casiphia/i.test(p.id)));
assert(book.chapters.every(c=>c.route.length===0));
assert(!book.chapters[7].lds.sourceIds.includes('cfm-ezra-2026'));
assert(!book.chapters[8].lds.sourceIds.includes('cfm-ezra-2026'));
assert.equal(book.people.length,35);
console.log('Ezra links passed: priestly namesakes, Persian officials, and uncertain journey locations.');
