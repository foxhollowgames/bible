import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../dist/',import.meta.url);
const app=await readFile(new URL('app.js',root),'utf8');
const people=JSON.parse(await readFile(new URL('data/books/2-samuel-people.json',root),'utf8')).people;
const book=JSON.parse(await readFile(new URL('data/books/2-samuel.json',root),'utf8'));
const functions=app.slice(app.indexOf('function entityLinkTerms('),app.indexOf('function linkedPersonProfileHtml('));
const context=vm.createContext({people,state:{chapter:21},entityLinkCache:{chapter:null,terms:[]},data:{places:[],regions:[],campaigns:[],events:[],ancientRoads:[],words:[]},mapDisplayName:s=>s,esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(functions,context);
const verse=(chapter,n)=>{context.state.chapter=chapter;return context.linkedEntityHtml(book.scripture[chapter].find(v=>v.verse===n).text,{verse:n});};
assert(verse(21,7).includes('data-person-id="mephibosheth-jonathan"'));
assert(!verse(21,7).includes('data-person-id="mephibosheth-saul"'));
assert(verse(21,8).includes('data-person-id="mephibosheth-saul"'));
assert(!verse(21,8).includes('data-person-id="mephibosheth-jonathan"'));
assert(verse(21,7).includes('data-person-id="jonathan-saul"'));
assert(verse(21,21).includes('data-person-id="jonathan-shimei"'));
assert(!verse(21,21).includes('data-person-id="jonathan-saul"'));
assert(verse(17,17).includes('data-person-id="en-rogel-servant"'));
assert(verse(17,19).includes('data-person-id="bahurim-woman"'));
assert(verse(17,25).includes('data-person-id="abigail-sister"'));
assert(!verse(17,25).includes('data-person-id="abigail"'));
assert(verse(9,6).includes('data-person-id="mephibosheth-jonathan"'));
assert(!verse(9,6).includes('data-person-id="mephibosheth-saul"'));
assert(verse(23,20).includes('data-person-id="benaiah"'));
assert(!verse(23,30).includes('data-person-id="benaiah"'));
assert(verse(23,11).includes('data-person-id="shammah-agee"'));
assert(!verse(23,25).includes('data-person-id="shammah-agee"'));
assert(verse(24,11).includes('data-person-id="gad"'));
assert(!verse(24,5).includes('data-person-id="gad"'));
assert(verse(11,21).includes('data-person-id="thembez-woman"'));
for(const n of [2,3,5])assert(!verse(11,n).includes('data-person-id="thembez-woman"'));
assert(!verse(14,27).includes('data-person-id="tekoa-woman"'));
console.log('Person links passed: same-chapter names, unnamed women, and chapter changes.');
