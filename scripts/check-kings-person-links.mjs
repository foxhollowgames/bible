import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../dist/',import.meta.url);
const app=await readFile(new URL('app.js',root),'utf8');
const people=JSON.parse(await readFile(new URL('data/books/1-kings-people.json',root),'utf8')).people;
const book=JSON.parse(await readFile(new URL('data/books/1-kings.json',root),'utf8'));
const functions=app.slice(app.indexOf('function entityLinkTerms('),app.indexOf('function linkedPersonProfileHtml('));
const context=vm.createContext({people,state:{chapter:1},entityLinkCache:{chapter:null,terms:[]},data:{places:[],regions:[],campaigns:[],events:[],ancientRoads:[],words:[]},mapDisplayName:s=>s,esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(functions,context);
const verse=(chapter,n)=>{context.state.chapter=chapter;return context.linkedEntityHtml(book.scripture[chapter].find(v=>v.verse===n).text,{verse:n});};
const linked=(chapter,n,id)=>verse(chapter,n).includes(`data-person-id="${id}"`);
assert(linked(5,1,'hiram'));assert(!linked(5,1,'hiram-artisan'));
assert(linked(7,13,'hiram-artisan'));assert(!linked(7,13,'hiram'));
assert(linked(9,11,'hiram'));assert(!linked(9,11,'hiram-artisan'));
assert(linked(16,1,'jehu-hanani'));assert(!linked(16,1,'jehu-nimshi'));
assert(linked(19,16,'jehu-nimshi'));assert(!linked(19,16,'jehu-hanani'));
assert(linked(15,18,'ben-hadad-asa'));assert(!linked(15,18,'ben-hadad-ahab'));
assert(linked(20,1,'ben-hadad-ahab'));assert(!linked(20,1,'ben-hadad-asa'));
assert(!linked(4,5,'nathan-prophet'));assert(!linked(4,18,'shimei-gera'));
assert(!linked(15,27,'ahijah-shiloh'));assert(!linked(4,2,'zadok'));
assert(linked(4,4,'zadok'));assert(!linked(4,3,'jehoshaphat'));
console.log('Kings person links passed: rulers, artisans, prophets, and namesakes.');
