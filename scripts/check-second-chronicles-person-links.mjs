import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../dist/',import.meta.url);
const app=await readFile(new URL('book-2-chronicles-app.js',root),'utf8');
const portraits=await readFile(new URL('book-2-chronicles-portraits.js',root),'utf8');
const people=JSON.parse(portraits.match(/export const people = (.*);/)[1]);
const book=JSON.parse(await readFile(new URL('data/books/2-chronicles.json',root),'utf8'));
const functions=app.slice(app.indexOf('function entityLinkTerms('),app.indexOf('function linkedPersonProfileHtml('));
const places=JSON.parse(await readFile(new URL('data/books/2-chronicles-native-content.json',root),'utf8')).places;
const context=vm.createContext({people,state:{chapter:1},entityLinkCache:{chapter:null,terms:[]},data:{places,regions:[],campaigns:[],events:[],ancientRoads:[],words:[]},mapDisplayName:s=>s,esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(functions,context);
const html=(chapter,n)=>{context.state.chapter=chapter;return context.linkedEntityHtml(book.scripture[chapter].find(v=>v.verse===n).text,{verse:n});};
const linked=(chapter,n,id)=>html(chapter,n).includes(`data-person-id="${id}"`);
assert(linked(2,3,'hiram'));assert(!linked(2,3,'hiram-artisan'));
assert(linked(2,13,'hiram-artisan'));assert(!linked(2,13,'hiram'));
assert(linked(15,1,'azariah-oded'));assert(linked(15,1,'oded-azariah'));
assert(linked(28,9,'oded-samaria'));assert(!linked(28,9,'oded-azariah'));
assert(linked(26,1,'azariah'));assert(!linked(26,1,'azariah-uzziah-priest'));
assert(linked(26,17,'azariah-uzziah-priest'));assert(!linked(26,17,'azariah'));
assert(linked(31,10,'azariah-hezekiah-priest'));
assert(linked(24,20,'zechariah-jehoiada'));assert(!linked(24,20,'zechariah-uzziah'));
assert(linked(26,5,'zechariah-uzziah'));assert(!linked(26,5,'zechariah-jehoiada'));
assert(linked(22,5,'joram-israel'));assert(!linked(22,6,'joram-israel'));assert(!linked(22,6,'jehoram-judah'));
assert(linked(25,17,'joash-israel'));assert(!linked(25,17,'joash-judah'));
assert(!linked(25,23,'joash-israel'));assert(!linked(25,23,'joash-judah'));
assert(linked(25,24,'obed-edom-amaziah'));assert(!html(25,24).includes('data-detail-id="edom"'));
assert(!html(2,14).includes('data-detail-id="dan"'));
assert(linked(34,20,'achbor'));assert(linked(34,8,'joah-joahaz'));
const asa=book.people.find(p=>p.id==='asa');
assert(/Syria/.test(asa.role)&&/Hanani/.test(asa.meaning),'Asa needs his later turn to Syria and his answer to Hanani');
assert.equal(people.asa.role,asa.role);
assert(!book.people.some(p=>p.meaning.includes('does not retell the full reign described in Kings and 2 Chronicles')));
console.log('Second Chronicles links passed: royal, priestly, prophetic, and place-name distinctions.');
