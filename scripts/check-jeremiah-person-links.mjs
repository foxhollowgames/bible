import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../dist/',import.meta.url);
const app=await readFile(new URL('app.js',root),'utf8');
const people=JSON.parse(await readFile(new URL('data/books/jeremiah-people.json',root),'utf8')).people;
const book=JSON.parse(await readFile(new URL('data/books/jeremiah.json',root),'utf8'));
const content=JSON.parse(await readFile(new URL('data/books/jeremiah-native-content.json',root),'utf8'));
const context=vm.createContext({people,state:{chapter:1},entityLinkCache:{chapter:null,terms:[]},data:{places:content.places,regions:[],campaigns:[],events:[],ancientRoads:[],words:[]},mapDisplayName:s=>s,esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')});
vm.runInContext(app.slice(app.indexOf('function entityLinkTerms('),app.indexOf('function linkedPersonProfileHtml(')),context);
const verse=(c,v)=>{context.state.chapter=c;return context.linkedEntityHtml(book.scripture[c].find(x=>x.verse===v).text,{verse:v});};
const reachable=new Set();
for(const c of book.chapters){
 context.state.chapter=c.chapter;
 const html=context.linkedEntityHtml(c.summary+' '+c.meaning)+book.scripture[c.chapter].map(v=>verse(c.chapter,v.verse)).join('');
 for(const m of html.matchAll(/data-person-id="([^"]+)"/g))reachable.add(m[1]);
}
assert.deepEqual(book.people.filter(p=>!reachable.has(p.id)).map(p=>p.id),[],'Each profile needs a reader link');
const original=JSON.parse(await readFile(new URL('../scripts/jeremiah-scripture-review.json',root),'utf8'));
assert.deepEqual(book.scripture,original);
assert.equal(Object.values(book.scripture).flat().length,1364);
const includes=(c,v,id)=>assert(verse(c,v).includes(`data-person-id="${id}"`),`${c}:${v} should link ${id}`);
const excludes=(c,v,id)=>assert(!verse(c,v).includes(`data-person-id="${id}"`),`${c}:${v} should not link ${id}`);
includes(20,1,'pashhur-immer');
includes(21,1,'pashhur-malchijah');
includes(38,1,'pashhur-malchijah');
assert.equal((verse(38,1).match(/data-person-id="pashhur-malchijah"/g)||[]).length,1,'Gedaliah’s father Pashhur stays unlinked');
includes(29,3,'zedekiah');excludes(29,21,'zedekiah');includes(29,21,'zedekiah-maaseiah');
includes(36,12,'zedekiah-hananiah');excludes(36,12,'zedekiah');
includes(29,3,'gemariah-hilkiah');includes(36,10,'gemariah-shaphan');
includes(35,3,'jaazaniah-rechabite');excludes(35,3,'jeremiah');
includes(40,8,'jezaniah-maacathite');includes(42,1,'jezaniah-hoshaiah');includes(43,2,'azariah-hoshaiah');
includes(37,15,'jonathan-scribe');includes(40,8,'jonathan-kareah');
includes(38,1,'hostile-officials');excludes(38,1,'gedaliah');includes(40,5,'gedaliah');
includes(36,26,'arrest-officers');includes(40,8,'seraiah-captain');includes(51,59,'seraiah-neriah');includes(52,24,'seraiah-priest');
excludes(38,1,'malchijah-royal');includes(38,6,'malchijah-royal');
excludes(52,1,'jeremiah');includes(52,1,'hamutal');
assert.deepEqual(book.chapters.filter(c=>c.route.length).map(c=>c.chapter),[29,39,40,52]);
assert(book.chapters.every(c=>!('year' in c)));
assert(book.sources.find(s=>s.id==='cfm-jeremiah-2').chapterCoverage.every(n=>n!==30));
console.log('Jeremiah passed: 66 reachable profiles, 1364 preserved verses, distinct same-name links, and four text-supported movements.');
